# Write a Python program to perform arithmetic operations: addition, subtraction, multiplication, and division.
firstNum=float(input("Enter first number=> "))
secondNum=float(input("Enter second number=> "))

#operation
sum=firstNum + secondNum
diff=firstNum - secondNum
multiplication= firstNum * secondNum
division= firstNum / secondNum
 
#display result's
print(f"Addition of {firstNum} and {secondNum} is => {sum}")
print(f"Difference of {firstNum} and {secondNum} is => {diff}")
print(f"Multiplication of {firstNum} and {secondNum} is => {multiplication}")
print(f"Division of {firstNum} and {secondNum} is => {division}")
